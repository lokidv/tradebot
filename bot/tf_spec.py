def is_known(tf):
    return tf in MINUTES


def _check(tf):
    if tf not in MINUTES:
        raise KeyError(f"تایم‌فریمِ ناشناخته: {tf!r} (مجاز: {', '.join(TFS)})")
    return tf


def minutes(tf):
    """دقیقه‌های یک کندل؛ تایم‌فریمِ ناشناخته ``KeyError`` می‌دهد (هرگز پیش‌فرضِ بی‌صدای ۶۰)."""
    return MINUTES[_check(tf)]


def bar_ms(tf):
    return BAR_MS[_check(tf)]


def bars_per_day(tf):
    return BARS_PER_DAY[_check(tf)]


def closed_between(tf, prev_s, now_s):
    """آیا کندلی از ``tf`` در بازهٔ ``(prev_s, now_s]`` (ثانیهٔ UTC، مرزهای هم‌ترازِ epoch) بسته شده؟"""
    sec = MINUTES[_check(tf)] * 60
    return int(now_s) // sec > int(prev_s) // sec
